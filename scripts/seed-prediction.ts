// Dev-only helper — NOT part of the app bundle, nothing here is imported
// by src/. Turns a small JSON seed file into ready-to-paste SQL that
// creates one episode and its predictions. Never connects to Supabase and
// never needs a service-role key — the generated SQL is meant to be pasted
// into the Supabase SQL editor by hand.
//
// Usage: node scripts/seed-prediction.ts seeds/example.json

import { readFileSync } from "node:fs";

type SeedEpisode = {
  title: string;
  episodeNumber?: number;
  airDate?: string;
  status?: string;
};

type SeedPrediction = {
  question: string;
  locksAt: string;
  options: string[];
};

type SeedFile = {
  channelSlug: string;
  episode: SeedEpisode;
  predictions: SeedPrediction[];
};

function fail(message: string): never {
  console.error(message);
  process.exit(1);
}

const path = process.argv[2];
if (!path) {
  fail("Usage: node scripts/seed-prediction.ts <path-to-seed.json>");
}

let raw: string;
try {
  raw = readFileSync(path, "utf8");
} catch (err) {
  fail(`Could not read ${path}: ${(err as Error).message}`);
}

let seed: SeedFile;
try {
  seed = JSON.parse(raw);
} catch (err) {
  fail(`${path} is not valid JSON: ${(err as Error).message}`);
}

// --- validation ---

if (!seed.channelSlug || typeof seed.channelSlug !== "string" || !seed.channelSlug.trim()) {
  fail("channelSlug is required and must be a non-empty string.");
}

if (!seed.episode || typeof seed.episode !== "object") {
  fail("episode is required.");
}

if (!seed.episode.title || typeof seed.episode.title !== "string" || !seed.episode.title.trim()) {
  fail("episode.title is required and must be a non-empty string.");
}

if (!Array.isArray(seed.predictions) || seed.predictions.length === 0) {
  fail("predictions must be a non-empty array — at least one prediction is required.");
}

seed.predictions.forEach((p, i) => {
  const label = `predictions[${i}]`;

  if (!p.question || typeof p.question !== "string" || !p.question.trim()) {
    fail(`${label}.question is required and must be a non-empty string.`);
  }

  if (!p.locksAt) {
    fail(
      `${label}.locksAt is required. A null locks_at means the prediction can never ` +
        `appear in "Closing Soon" — the only reachable way to lock in a pick on /predict — ` +
        `so it would be unpickable.`
    );
  }
  if (isNaN(Date.parse(p.locksAt))) {
    fail(`${label}.locksAt ("${p.locksAt}") is not a valid date.`);
  }

  if (!Array.isArray(p.options) || p.options.length < 2) {
    fail(`${label}.options must be an array with at least 2 options.`);
  }
  p.options.forEach((o, j) => {
    if (!o || typeof o !== "string" || !o.trim()) {
      fail(`${label}.options[${j}] must be a non-empty string.`);
    }
  });
  const seen = new Set<string>();
  for (const o of p.options) {
    if (seen.has(o)) {
      fail(`${label} has a duplicate option label: "${o}".`);
    }
    seen.add(o);
  }
});

// --- SQL generation ---

function sqlString(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

function sqlLiteralOrNull(value: string | number | undefined | null): string {
  if (value === undefined || value === null) return "null";
  return typeof value === "number" ? String(value) : sqlString(value);
}

function buildSql(seed: SeedFile, sourcePath: string): string {
  const channelSlug = sqlString(seed.channelSlug);
  const episodeTitle = sqlString(seed.episode.title);
  const episodeNumber = sqlLiteralOrNull(seed.episode.episodeNumber);
  const airDate = seed.episode.airDate ? `${sqlString(seed.episode.airDate)}::timestamptz` : "null";
  const episodeStatus = sqlString(seed.episode.status ?? "upcoming");

  const lines: string[] = [];
  lines.push(`-- Generated by scripts/seed-prediction.ts from ${sourcePath}`);
  lines.push("do $$");
  lines.push("declare");
  lines.push("  v_channel_id uuid;");
  lines.push("  v_episode_id uuid;");
  lines.push("  v_prediction_id uuid;");
  lines.push("begin");
  lines.push(`  select id into v_channel_id from channels where slug = ${channelSlug};`);
  lines.push("  if v_channel_id is null then");
  lines.push(`    raise exception 'No channel found with slug %', ${channelSlug};`);
  lines.push("  end if;");
  lines.push("");
  lines.push("  insert into episodes (channel_id, title, episode_number, air_date, status)");
  lines.push(
    `  values (v_channel_id, ${episodeTitle}, ${episodeNumber}, ${airDate}, ${episodeStatus})`
  );
  lines.push("  returning id into v_episode_id;");

  seed.predictions.forEach((p, i) => {
    const question = sqlString(p.question);
    const locksAt = `${sqlString(p.locksAt)}::timestamptz`;

    lines.push("");
    lines.push(`  -- Prediction ${i + 1}`);
    lines.push("  insert into predictions (episode_id, channel_id, question, status, locks_at)");
    lines.push(
      `  values (v_episode_id, v_channel_id, ${question}, 'open', ${locksAt})`
    );
    lines.push("  returning id into v_prediction_id;");
    lines.push("");
    lines.push("  insert into prediction_options (prediction_id, label, sort_order) values");
    const optionRows = p.options.map(
      (o, j) => `    (v_prediction_id, ${sqlString(o)}, ${j})`
    );
    lines.push(optionRows.join(",\n") + ";");
  });

  lines.push("end $$;");
  lines.push("");
  lines.push("-- Verify what was just created for this episode.");
  lines.push("select");
  lines.push("  p.question,");
  lines.push("  c.name as channel_name,");
  lines.push("  p.locks_at,");
  lines.push("  array_agg(po.label order by po.sort_order) as options");
  lines.push("from predictions p");
  lines.push("join channels c on c.id = p.channel_id");
  lines.push("join episodes e on e.id = p.episode_id");
  lines.push("join prediction_options po on po.prediction_id = p.id");
  lines.push(`where c.slug = ${channelSlug}`);
  lines.push(`  and e.title = ${episodeTitle}`);
  lines.push("group by p.id, c.name, p.locks_at");
  lines.push("order by p.locks_at;");

  return lines.join("\n");
}

console.log(buildSql(seed, path));
